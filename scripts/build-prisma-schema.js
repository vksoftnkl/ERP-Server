#!/usr/bin/env node
const { readdirSync, readFileSync, writeFileSync } = require('node:fs');
const { join, relative, resolve } = require('node:path');

const prismaDir = resolve(process.cwd(), 'prisma');
const baseSchemaPath = join(prismaDir, 'base.prisma');
const outputSchemaPath = join(prismaDir, 'schema.prisma');

const walk = (dirPath) => {
  const entries = readdirSync(dirPath, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = join(dirPath, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(fullPath));
      continue;
    }

    files.push(fullPath);
  }

  return files;
};

const isModelSchema = (absolutePath) =>
  absolutePath.endsWith('.prisma') &&
  absolutePath !== baseSchemaPath &&
  absolutePath !== outputSchemaPath;

const hasConfigBlock = (schemaContent) => /^\s*(generator|datasource)\s+\w+/m.test(schemaContent);

const baseSchema = readFileSync(baseSchemaPath, 'utf8').trimEnd();
const modelSchemaPaths = walk(prismaDir)
  .filter(isModelSchema)
  .sort((a, b) => a.localeCompare(b));

const sourceSchemas = modelSchemaPaths.map((absolutePath) => {
  const content = readFileSync(absolutePath, 'utf8').trim();

  if (hasConfigBlock(content)) {
    throw new Error(
      `Only ${relative(process.cwd(), baseSchemaPath)} can define datasource/generator. Found in ${relative(
        process.cwd(),
        absolutePath,
      )}.`,
    );
  }

  return {
    relativePath: relative(process.cwd(), absolutePath),
    content,
  };
});

let mergedSchema = `// AUTO-GENERATED FILE. DO NOT EDIT.\n`;
mergedSchema += `// Generated by scripts/build-prisma-schema.js\n\n`;
mergedSchema += `${baseSchema}\n\n`;

for (const schema of sourceSchemas) {
  mergedSchema += `// ----- ${schema.relativePath} -----\n`;
  mergedSchema += `${schema.content}\n\n`;
}

writeFileSync(outputSchemaPath, mergedSchema, 'utf8');

console.log(
  `Built ${relative(process.cwd(), outputSchemaPath)} from ${1 + sourceSchemas.length} schema file(s).`,
);
