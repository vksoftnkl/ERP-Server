-- A replacement that no longer exists cannot get a year, and both
-- ck_apd_replaced_pair and fk_apd_replaced_by would reject the row. Such a
-- pointer was already dangling under the old FK; clear it rather than fail the
-- migration on data that was never valid. ck_apd_replaced then forces the row
-- off the REPLACED status, which is what it now is: not replaced by anything.
UPDATE accounts.acc_pdc_register
SET apd_replaced_by_id = NULL,
    apd_status = CASE WHEN apd_status = 'REPLACED' THEN 'HELD' ELSE apd_status END
WHERE apd_replaced_by_id IS NOT NULL
  AND apd_replaced_by_acc_year IS NULL;

