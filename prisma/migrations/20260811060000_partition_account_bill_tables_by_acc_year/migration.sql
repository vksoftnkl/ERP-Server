-- Convert the four remaining accounts tables --
--
--   accounts.acc_bill_adjustment   settlement rows against a bill
--   accounts.acc_bills_balance     one row per bill
--   accounts.acc_opening_balance   per-ledger opening balance per FY
--   accounts.acc_pdc_register      post-dated instrument register
--
-- -- to declaratively LIST-partitioned tables keyed on their own acc_year
-- column, the way acc_voucher_header / acc_vouchers / acc_tender_detail and
-- the sales documents already are. Each keeps the year it was created in:
--
--   acc_bills_balance   -> abl_acc_year (FY the bill originated in)
--   acc_bill_adjustment -> aba_acc_year (FY the settlement happened in)
--   acc_opening_balance -> op_acc_year  (the FY the balance opens)
--   acc_pdc_register    -> apd_acc_year (FY the instrument was received in)
--
-- Worth knowing before a year is ever detached: three of these four are
-- cross-year by nature. A bill stays open across year end, a settlement
-- routinely lands in a later FY than the bill it clears, and a cheque matures
-- in a later FY than the one it arrived in. The row never moves partition, so
-- the partition says "where it started", not "where the money is". Outstanding
-- and ageing reads are company-wide and carry no year filter, so they scan
-- every partition; and detaching a closed year takes still-open bills with it.
-- Pruning only helps reads that do filter on the year column.
--
-- Postgres cannot ALTER an ordinary table into a partitioned one, so all four
-- are rebuilt: the existing tables are parked under `_unpart` names, the
-- partitioned parents are created with the same columns, their rows are copied
-- over, and the parked tables are dropped.
--
-- What changes beyond the storage layout:
--
--   1. Every primary key gains the partition key -- pk_acc_bills is now
--      (abl_id, abl_acc_year), pk_acc_bill_adjustment (aba_id, aba_acc_year),
--      pk_acc_opening (op_id, op_acc_year) and pk_acc_pdc_register
--      (apd_id, apd_acc_year). Postgres requires every unique constraint on a
--      partitioned table to contain the partition key, so callers address a row
--      by the pair, not by the id alone.
--   2. ux_aba_voucher_row gains aba_acc_year for the same reason. A settlement
--      row carries the FY of its own voucher, so "one row per voucher line
--      position" is unchanged in practice. ux_abl_bill_refno, ux_op_scope and
--      ux_apd_instrument already contained the year.
--   3. fk_aba_bill points at a composite key now, so acc_bill_adjustment gains
--      aba_bill_acc_year -- the FY of the BILL, which is exactly the column
--      that differs from aba_acc_year when a bill is cleared after year end.
--   4. fk_av_doc (acc_vouchers -> acc_bills_balance) likewise, so acc_vouchers
--      gains av_doc_acc_year, kept null-or-set together with av_doc_id
--      (ck_av_doc_pair).
--   5. fk_apd_replaced_by -- the replacement self-reference -- gains
--      apd_replaced_by_acc_year, kept null-or-set together with
--      apd_replaced_by_id (ck_apd_replaced_pair). This mirrors
--      sq_parent_acc_year on sale_quotation (20260810130000).
--
-- The rebuild also restores what acc_bills_balance lost when
-- 20260811052010_account_vouchersfiled_name_changed_table recreated it through
-- `prisma migrate dev`: the generated abl_pending_amount column, the five
-- indexes and every CHECK constraint declared in 20260806090000. They are
-- listed as DB-only objects in prisma/accounts/AccountBillsBalance.prisma and
-- had silently gone missing from the database.
--
-- Prisma Migrate can express none of PARTITION BY, composite partition-aware
-- primary keys, generated columns, partial indexes or CHECK constraints, so
-- this migration is hand-written rather than generated by `prisma migrate dev`.


-- ───────────────────────────────────────────────────────────────────────────
