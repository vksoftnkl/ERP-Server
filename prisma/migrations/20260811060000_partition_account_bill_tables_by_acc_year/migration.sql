        REFERENCES accounts.acc_pdc_register (apd_id, apd_acc_year) MATCH SIMPLE
        ON UPDATE CASCADE ON DELETE RESTRICT;


-- ───────────────────────────────────────────────────────────────────────────
--  8. Prove nothing was lost, then drop the parked tables
-- ───────────────────────────────────────────────────────────────────────────

DO
$$
    DECLARE
        v_old bigint;
        v_new bigint;
    BEGIN
        SELECT count(*) INTO v_old FROM accounts.acc_bills_balance_unpart;
        SELECT count(*) INTO v_new FROM accounts.acc_bills_balance;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'acc_bills_balance copy lost rows: % -> %', v_old, v_new;
        END IF;

        SELECT count(*) INTO v_old FROM accounts.acc_bill_adjustment_unpart;
        SELECT count(*) INTO v_new FROM accounts.acc_bill_adjustment;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'acc_bill_adjustment copy lost rows: % -> % (a settlement pointing at a bill that does not exist)', v_old, v_new;
        END IF;

        SELECT count(*) INTO v_old FROM accounts.acc_opening_balance_unpart;
        SELECT count(*) INTO v_new FROM accounts.acc_opening_balance;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'acc_opening_balance copy lost rows: % -> %', v_old, v_new;
        END IF;

        SELECT count(*) INTO v_old FROM accounts.acc_pdc_register_unpart;
        SELECT count(*) INTO v_new FROM accounts.acc_pdc_register;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'acc_pdc_register copy lost rows: % -> %', v_old, v_new;
        END IF;
    END;
$$;

DROP TABLE accounts.acc_bill_adjustment_unpart;
DROP TABLE accounts.acc_pdc_register_unpart;
DROP TABLE accounts.acc_opening_balance_unpart;
DROP TABLE accounts.acc_bills_balance_unpart;


-- ───────────────────────────────────────────────────────────────────────────
--  9. Re-point acc_vouchers at the bill's composite key
--
--  av_doc_id is the hard link from a ledger line to the bill it belongs to.
--  The bill is addressed by (abl_id, abl_acc_year) now, so the year comes
--  along -- and it is the BILL's year, not av_acc_year, which is the voucher's.
-- ───────────────────────────────────────────────────────────────────────────

ALTER TABLE accounts.acc_vouchers ADD COLUMN av_doc_acc_year character(9);

UPDATE accounts.acc_vouchers AS v
SET av_doc_acc_year = bill.abl_acc_year
FROM accounts.acc_bills_balance AS bill
WHERE v.av_doc_id IS NOT NULL
  AND bill.abl_id = v.av_doc_id;

-- Same reasoning as the PDC replacement pointer above: a doc id with no bill
-- behind it could not have satisfied the old fk_av_doc.
UPDATE accounts.acc_vouchers
SET av_doc_id = NULL
WHERE av_doc_id IS NOT NULL
  AND av_doc_acc_year IS NULL;

ALTER TABLE accounts.acc_vouchers
    ADD CONSTRAINT ck_av_doc_pair CHECK (
        (av_doc_id IS NULL) = (av_doc_acc_year IS NULL));

ALTER TABLE accounts.acc_vouchers
    ADD CONSTRAINT fk_av_doc FOREIGN KEY (av_doc_id, av_doc_acc_year)
        REFERENCES accounts.acc_bills_balance (abl_id, abl_acc_year) MATCH SIMPLE
        ON UPDATE CASCADE ON DELETE RESTRICT;

COMMENT ON COLUMN accounts.acc_vouchers.av_doc_acc_year IS
    'FY of the bill in av_doc_id — the bill''s own year, not the voucher''s. Second half of fk_av_doc, set exactly when av_doc_id is (ck_av_doc_pair).';
