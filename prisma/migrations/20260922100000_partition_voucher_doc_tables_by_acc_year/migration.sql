-- ───────────────────────────────────────────────────────────────────────────
--  6. Partitions for every year that exists
--
--  Three sources, because none of them alone is complete on every deployment:
--  the fiscal years on record, the years that already have a sale_bill
--  partition (the convention 20260922040000 used), and -- the one that matters
--  for the copy below -- every acc_year actually present in the parked rows.
--  A year in the data but not in fiscal_years would otherwise fail the INSERT
--  with "no partition of relation ... found for row".
-- ───────────────────────────────────────────────────────────────────────────

DO $partitions$
DECLARE
    v_year   text;
    v_suffix text;
BEGIN
    FOR v_year IN
        SELECT DISTINCT y FROM (
            SELECT btrim(fy_year_name) AS y
              FROM public.fiscal_years
             WHERE is_deleted = false
            UNION
            SELECT replace(substring(c.relname from '([0-9]{4}_[0-9]{4})$'), '_', '-')
              FROM pg_class c
              JOIN pg_inherits i ON i.inhrelid = c.oid
              JOIN pg_class    p ON p.oid      = i.inhparent
             WHERE p.relname = 'sale_bill'
               AND c.relname ~ '[0-9]{4}_[0-9]{4}$'
            UNION SELECT btrim(gdr_acc_year) FROM accounts.acc_voucher_doc_register_unpart
            UNION SELECT btrim(vtx_acc_year) FROM accounts.acc_voucher_doc_detail_unpart
            UNION SELECT btrim(gde_acc_year) FROM accounts.acc_voucher_doc_einvoice_unpart
            UNION SELECT btrim(gdw_acc_year) FROM accounts.acc_voucher_doc_ewaybill_unpart
        ) s
        WHERE y ~ '^[0-9]{4}-[0-9]{4}$'
        ORDER BY 1
    LOOP
        v_suffix := replace(v_year, '-', '_');

        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_voucher_doc_register FOR VALUES IN (%L)',
            'acc_voucher_doc_register_' || v_suffix, v_year);
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_voucher_doc_detail FOR VALUES IN (%L)',
            'acc_voucher_doc_detail_' || v_suffix, v_year);
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_voucher_doc_einvoice FOR VALUES IN (%L)',
            'acc_voucher_doc_einvoice_' || v_suffix, v_year);
        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_voucher_doc_ewaybill FOR VALUES IN (%L)',
            'acc_voucher_doc_ewaybill_' || v_suffix, v_year);

        RAISE NOTICE 'acc_voucher_doc_* partitions ensured for %', v_year;
    END LOOP;
END
$partitions$;


