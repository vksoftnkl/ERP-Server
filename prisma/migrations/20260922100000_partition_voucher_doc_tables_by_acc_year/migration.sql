-- Convert the four GST document tables --
--
--   accounts.acc_voucher_doc_register   one row per outward/inward document
--   accounts.acc_voucher_doc_detail     its HSN/tax lines
--   accounts.acc_voucher_doc_einvoice   the IRN leg of that document
--   accounts.acc_voucher_doc_ewaybill   the e-way bill leg of that document
--
-- -- to declaratively LIST-partitioned tables keyed on their own acc_year
-- column, the way sale_bill (20260731070026), the account bill tables
-- (20260811060000), the vouchers (20260915120000) and the six sales documents
-- (20260921200000) already are:
--
--   acc_voucher_doc_register -> gdr_acc_year
--   acc_voucher_doc_detail   -> vtx_acc_year
--   acc_voucher_doc_einvoice -> gde_acc_year
--   acc_voucher_doc_ewaybill -> gdw_acc_year
--
-- This is the one band that is READ a whole year at a time: GSTR-1 and GSTR-3B
-- are filed per return period out of the register and its details, and the
-- annual return reads a full financial year. Every one of those queries already
-- carries the year in its WHERE clause, so they prune to a single partition;
-- and a closed year detaches as a unit once its returns are filed and its
-- e-invoices can no longer be cancelled. Unlike the bill tables, nothing here
-- is cross-year by nature: a document, its IRN and its e-way bill all belong to
-- the year the document was raised in and never move.
--
-- Postgres cannot ALTER an ordinary table into a partitioned one, so all four
-- are rebuilt: the existing tables are parked under `_unpart` names, the
-- partitioned parents are created with the same columns, their rows are copied
-- over, and the parked tables are dropped.
--
-- What changes beyond the storage layout:
--
--   1. Every primary key gains the partition key, because Postgres requires
--      each unique constraint on a partitioned table to contain it. The four
--      are now (gdr_id, gdr_acc_year), (vtx_id, vtx_acc_year),
--      (gde_id, gde_acc_year) and (gdw_id, gdw_acc_year). They are also named
--      at last -- pk_acc_voucher_doc_* rather than the *_pkey that Prisma
--      generated in 20260323073223. A caller addresses a row by the pair, not
--      by the id alone.
--   2. The three links to the register -- fk_acc_voucher_doc_detail_gdr,
--      fk_gde_gdr and fk_gdw_gdr -- point at that composite key now. No column
--      had to be added: vtx_acc_year, gde_acc_year and gdw_acc_year already
--      carry the register row's year, which is what makes this band cheaper to
--      partition than the bill tables were.
--   3. uq_gde_gdr and uq_gdw_gdr gain the year for the same reason. They still
--      say "at most one IRN / e-way bill per document", since a document lives
--      in exactly one year.
--   4. Three partial unique indexes gain the year as a trailing column:
--      uq_acc_voucher_doc_register_source, uq_acc_voucher_doc_einvoice_irn and
--      uq_acc_voucher_doc_ewaybill_no. This is the one real weakening here --
--      the same IRN or e-way bill number could now be stored twice in two
--      different years. In practice it cannot happen: an IRN is a hash of
--      supplier GSTIN + document type + document number + FINANCIAL YEAR, and
--      an e-way bill number is a portal-issued running number, so neither
--      repeats across years. The year is trailing, so lookups by IRN or by
--      e-way bill number alone still use the index.
--      uq_acc_voucher_doc_register_voucher and uq_acc_voucher_doc_register_doc
--      already contained gdr_acc_year.
--
-- Column order follows the prisma/accounts/*.prisma field order, which the
-- rebuild is a free opportunity to restore: gdr_igst_on_intra (20260917120000)
-- and the provenance/reconciliation columns on the e-invoice and e-way bill
-- (20260921120000, 20260922020000) had drifted to the end of the tables.
--
-- Prisma Migrate can express none of PARTITION BY, composite partition-aware
-- primary keys, partial indexes or CHECK constraints, so this migration is
-- hand-written rather than generated by `prisma migrate dev`.


-- ───────────────────────────────────────────────────────────────────────────
