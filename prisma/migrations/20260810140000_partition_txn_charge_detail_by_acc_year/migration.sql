-- ───────────────────────────────────────────────────────────────────────────
--  6. Prove nothing was lost, then drop the old table
-- ───────────────────────────────────────────────────────────────────────────

DO
$$
    DECLARE
        v_old bigint;
        v_new bigint;
    BEGIN
        SELECT count(*) INTO v_old FROM sales.sale_charge_detail;
        SELECT count(*) INTO v_new FROM public.txn_charge_detail;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'sale_charge_detail copy lost rows: % -> %', v_old, v_new;
        END IF;
    END;
$$;

DROP TABLE sales.sale_charge_detail;
