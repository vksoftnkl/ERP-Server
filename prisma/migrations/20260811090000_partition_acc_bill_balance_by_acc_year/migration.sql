-- ───────────────────────────────────────────────────────────────────────────
--  7. The adjustment learns the bill's year
--
--  Altered in place: acc_bill_adjustment is already partitioned and none of its
--  own keys change. abj_bill_acc_year is the FY the bill was RAISED in, which
--  is not abj_acc_year whenever a bill is cleared after year end — that gap is
--  the whole reason the two tables are partitioned on different years.
-- ───────────────────────────────────────────────────────────────────────────

ALTER TABLE accounts.acc_bill_adjustment
    ADD COLUMN IF NOT EXISTS abj_bill_acc_year         character(9),
    ADD COLUMN IF NOT EXISTS abj_against_bill_acc_year character(9);

UPDATE accounts.acc_bill_adjustment AS adj
SET abj_bill_acc_year = bill.abl_acc_year
FROM accounts.acc_bill_balance AS bill
WHERE bill.abl_id = adj.abj_bill_id;

UPDATE accounts.acc_bill_adjustment AS adj
SET abj_against_bill_acc_year = bill.abl_acc_year
FROM accounts.acc_bill_balance AS bill
WHERE adj.abj_against_bill_id IS NOT NULL
  AND bill.abl_id = adj.abj_against_bill_id;

-- A settlement whose bill has vanished could not have existed under the old
-- fk_abj_bill, and abj_bill_id is NOT NULL, so there is nothing to clear —
-- fail loudly instead.
DO
$$
    DECLARE
        v_orphans bigint;
    BEGIN
        SELECT count(*) INTO v_orphans
        FROM accounts.acc_bill_adjustment
        WHERE abj_bill_acc_year IS NULL;
        IF v_orphans > 0 THEN
            RAISE EXCEPTION
                'acc_bill_adjustment has % row(s) pointing at a bill that does not exist', v_orphans;
        END IF;

        SELECT count(*) INTO v_orphans
        FROM accounts.acc_bill_adjustment
        WHERE abj_against_bill_id IS NOT NULL
          AND abj_against_bill_acc_year IS NULL;
        IF v_orphans > 0 THEN
            RAISE EXCEPTION
                'acc_bill_adjustment has % row(s) whose against-bill does not exist', v_orphans;
        END IF;
    END;
$$;

ALTER TABLE accounts.acc_bill_adjustment
    ALTER COLUMN abj_bill_acc_year SET NOT NULL;

ALTER TABLE accounts.acc_bill_adjustment
    ADD CONSTRAINT ck_abj_bill_acc_year CHECK (
        abj_bill_acc_year ~ '^[0-9]{4}-[0-9]{4}$'
        AND RIGHT(abj_bill_acc_year, 4)::int = LEFT(abj_bill_acc_year, 4)::int + 1),
    -- The against-bill pointer addresses a composite key, so both halves move
    -- together. ck_abj_against already decides WHEN it must be set.
    ADD CONSTRAINT ck_abj_against_bill_pair CHECK (
        (abj_against_bill_id IS NULL) = (abj_against_bill_acc_year IS NULL));

ALTER TABLE accounts.acc_bill_adjustment
    ADD CONSTRAINT fk_abj_bill
        FOREIGN KEY (abj_bill_id, abj_bill_acc_year)
        REFERENCES accounts.acc_bill_balance (abl_id, abl_acc_year) MATCH SIMPLE
        ON UPDATE CASCADE ON DELETE RESTRICT,
    ADD CONSTRAINT fk_abj_against_bill
        FOREIGN KEY (abj_against_bill_id, abj_against_bill_acc_year)
        REFERENCES accounts.acc_bill_balance (abl_id, abl_acc_year) MATCH SIMPLE
        ON UPDATE CASCADE ON DELETE RESTRICT;

-- Both halves of the bill key, so the roll-up and the bill drill-down read the
-- index alone. Replaces the id-only ix_abj_bill from 20260811080000.
DROP INDEX IF EXISTS accounts.ix_abj_bill;
CREATE INDEX ix_abj_bill
    ON accounts.acc_bill_adjustment USING btree
    (abj_bill_id, abj_bill_acc_year, abj_adj_date)
    WITH (fillfactor=100, deduplicate_items=True)
    WHERE abj_is_deleted = false;

COMMENT ON COLUMN accounts.acc_bill_adjustment.abj_bill_acc_year IS
    'FY of the bill being settled — the bill''s own year, not abj_acc_year. Second half of fk_abj_bill, which addresses the bill''s composite (abl_id, abl_acc_year) key.';
COMMENT ON COLUMN accounts.acc_bill_adjustment.abj_against_bill_acc_year IS
    'FY of the bill on the other side of a two-sided settlement. Second half of fk_abj_against_bill, set exactly when abj_against_bill_id is (ck_abj_against_bill_pair).';


-- ───────────────────────────────────────────────────────────────────────────
--  8. Prove nothing was lost, then drop the parked table
-- ───────────────────────────────────────────────────────────────────────────

DO
$$
    DECLARE
        v_old bigint;
        v_new bigint;
    BEGIN
        SELECT count(*) INTO v_old FROM accounts.acc_bill_balance_unpart;
        SELECT count(*) INTO v_new FROM accounts.acc_bill_balance;
        IF v_old <> v_new THEN
            RAISE EXCEPTION 'acc_bill_balance copy lost rows: % -> %', v_old, v_new;
        END IF;
    END;
$$;

DROP TABLE accounts.acc_bill_balance_unpart;


-- ───────────────────────────────────────────────────────────────────────────
--  9. Point acc_vouchers back at the bill's composite key
--
--  av_doc_acc_year already exists and is already paired with av_doc_id by
--  ck_av_doc_pair (20260811060000 added both; 20260811080000 dropped only the
--  foreign key). It is backfilled again here rather than trusted, because
--  nothing enforced it while fk_av_doc addressed abl_id alone.
-- ───────────────────────────────────────────────────────────────────────────

UPDATE accounts.acc_vouchers AS v
SET av_doc_acc_year = bill.abl_acc_year
FROM accounts.acc_bill_balance AS bill
WHERE v.av_doc_id IS NOT NULL
  AND bill.abl_id = v.av_doc_id
  AND (v.av_doc_acc_year IS DISTINCT FROM bill.abl_acc_year);

-- Same reasoning as the parent pointer above: a doc id with no bill behind it
-- could not have satisfied the old fk_av_doc.
UPDATE accounts.acc_vouchers
SET av_doc_id = NULL,
    av_doc_acc_year = NULL
WHERE av_doc_id IS NOT NULL
  AND av_doc_acc_year IS NULL;

ALTER TABLE accounts.acc_vouchers
    ADD CONSTRAINT fk_av_doc FOREIGN KEY (av_doc_id, av_doc_acc_year)
        REFERENCES accounts.acc_bill_balance (abl_id, abl_acc_year) MATCH SIMPLE
        ON UPDATE CASCADE ON DELETE RESTRICT;

COMMENT ON COLUMN accounts.acc_vouchers.av_doc_acc_year IS
    'FY of the bill in av_doc_id — the bill''s own year, not the voucher''s. Second half of fk_av_doc, set exactly when av_doc_id is (ck_av_doc_pair).';
