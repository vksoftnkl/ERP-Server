-- ───────────────────────────────────────────────────────────────────────────
--  4. Teach public.ensure_acc_year_partitions about the bill again
--
--  Same helper as 20260804112944 (extended by 20260808132323, 20260810130000,
--  20260810140000, 20260810160000, 20260811060000 and 20260811080000).
--  acc_bill_balance comes back into the list; everything else is unchanged.
--  Idempotent — call it whenever a fiscal year is opened:
--
--      SELECT public.ensure_acc_year_partitions('2027-2028');
-- ───────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.ensure_acc_year_partitions(p_acc_year character(9))
    RETURNS void
    LANGUAGE plpgsql
AS
$$
DECLARE
    v_year   text := btrim(p_acc_year);
    v_suffix text;
BEGIN
    -- The partition bound is a literal, so the year is validated rather than
    -- interpolated blind. char(9) makes 'YYYY-YYYY' the only well-formed value.
    IF v_year !~ '^[0-9]{4}-[0-9]{4}$' THEN
        RAISE EXCEPTION 'Invalid accounting year %, expected YYYY-YYYY', p_acc_year;
    END IF;

    v_suffix := replace(v_year, '-', '_');

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_bill FOR VALUES IN (%L)',
        'sale_bill_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_bill_item FOR VALUES IN (%L)',
        'sale_bill_item_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_tender_detail FOR VALUES IN (%L)',
        'acc_tender_detail_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.%I PARTITION OF public.txn_status_log FOR VALUES IN (%L)',
        'txn_status_log_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.%I PARTITION OF public.txn_charge_detail FOR VALUES IN (%L)',
        'txn_charge_detail_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.%I PARTITION OF public.txn_hold FOR VALUES IN (%L)',
        'txn_hold_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_order FOR VALUES IN (%L)',
        'sale_order_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_order_item FOR VALUES IN (%L)',
        'sale_order_item_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_order_advance_alloc FOR VALUES IN (%L)',
        'sale_order_advance_alloc_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_quotation FOR VALUES IN (%L)',
        'sale_quotation_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS sales.%I PARTITION OF sales.sale_quotation_item FOR VALUES IN (%L)',
        'sale_quotation_item_' || v_suffix, v_year);

    -- The bill is partitioned again as of 20260811090000: on the FY it was
    -- RAISED in, which it keeps for life.
    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_bill_balance FOR VALUES IN (%L)',
        'acc_bill_balance_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_bill_adjustment FOR VALUES IN (%L)',
        'acc_bill_adjustment_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_opening_balance FOR VALUES IN (%L)',
        'acc_opening_balance_' || v_suffix, v_year);

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS accounts.%I PARTITION OF accounts.acc_pdc_register FOR VALUES IN (%L)',
        'acc_pdc_register_' || v_suffix, v_year);
END;
$$;

COMMENT ON FUNCTION public.ensure_acc_year_partitions(character(9)) IS
    'Idempotently creates the sale_bill / sale_bill_item / acc_tender_detail / txn_status_log / txn_charge_detail / txn_hold / sale_order / sale_order_item / sale_order_advance_alloc / sale_quotation / sale_quotation_item / acc_bill_balance / acc_bill_adjustment / acc_opening_balance / acc_pdc_register LIST partitions for one accounting year (YYYY-YYYY). Run it whenever a fiscal year is opened.';


-- ───────────────────────────────────────────────────────────────────────────
--  5. Partitions
--
--  Every year on record in fiscal_years, plus — belt and braces — any year the
--  parked rows actually carry, so nothing can fail to find a home below. Every
--  other parent in the helper already has its partitions, and
--  CREATE TABLE IF NOT EXISTS passes straight over them.
-- ───────────────────────────────────────────────────────────────────────────

DO
$$
    DECLARE
        v_year text;
    BEGIN
        FOR v_year IN
            SELECT DISTINCT btrim(fy_year_name)
            FROM public.fiscal_years
            WHERE is_deleted = false
              AND btrim(fy_year_name) ~ '^[0-9]{4}-[0-9]{4}$'
            UNION
            SELECT DISTINCT btrim(abl_acc_year) FROM accounts.acc_bill_balance_unpart
            ORDER BY 1
            LOOP
                IF v_year !~ '^[0-9]{4}-[0-9]{4}$' THEN
                    RAISE EXCEPTION 'acc_bill_balance carries accounting year %, which is not YYYY-YYYY', v_year;
                END IF;
                PERFORM public.ensure_acc_year_partitions(v_year::character(9));
            END LOOP;
    END;
$$;


-- ───────────────────────────────────────────────────────────────────────────
--  6. Move the rows over, then close the parent self-reference
--
--  abl_pending_amount and abl_status are generated, so they are neither listed
--  nor copied. abl_parent_acc_year is a new column, read from the parent bill
--  rather than copied — the LEFT JOIN is against the parked table, which still
--  holds every row at this point.
--
--  A parent that no longer exists could not have satisfied the old fk_abl_parent
--  either, and would now fail ck_abl_parent_pair as well, so the dangling
--  pointer is dropped on the way through rather than failing the migration on
--  data that was never valid. (If such a row is an INTEREST bill, ck_abl_parent
--  rejects it and the migration stops — interest with no bill behind it is a
--  data problem somebody has to look at, not one to paper over.)
-- ───────────────────────────────────────────────────────────────────────────

INSERT INTO accounts.acc_bill_balance (
    abl_id, abl_company_id, abl_branch_id, abl_tenant_id, abl_acc_year,
    abl_party_id, abl_salesman_id, abl_agent_id, abl_bill_type,
    abl_src_module, abl_src_doc_type, abl_src_doc_id, abl_src_acc_year,
    abl_parent_bill_id, abl_parent_acc_year,
    abl_voucher_id, abl_voucher_line_id, abl_voucher_type_id, abl_voucher_no,
    abl_voucher_date, abl_voucher_refno,
    abl_doc_refno, abl_doc_date, abl_due_date, abl_credit_days, abl_grace_days,
    abl_dr_cr, abl_narration,
    abl_bill_amount, abl_alloc_amount, abl_disc_amount, abl_writeoff_amount,
    abl_settled_on,
    abl_is_active, abl_is_deleted, abl_sync_date, abl_created_on, abl_created_by,
    abl_modified_on, abl_modified_by
)
SELECT
