-- ═══════════════════════════════════════════════════════════════════════════
--  accounts.acc_ledger_map  —  fill it, all 22 roles
--
--  ── Why this exists ──────────────────────────────────────────────────────
--  accounts.acc_ledger_role has 22 roles. accounts.acc_ledger_map has ZERO
--  rows. So resolveLedgerForRole() (ledger-map.helper.ts) answers null for
--  every role, and every posting path that asks for a ledger by role gets
--  nothing back:
--
--      · the sale bill's revenue, tax, round-off and discount legs
--      · the receipt / payment / cheque flows
--      · the voucher register
--      · the opening-balance screen's plug (OPENING_DIFFERENCE) and
--        carry-forward's profit destination (RETAINED_EARNINGS), which
--        20260915090000 added roles for and nothing has ever answered
--
--  ── Why the work is in a FUNCTION and not in this file's body ────────────
--  Migrations run BEFORE seeds (`db:deploy` = migrate deploy && seed:run),
--  and the chart of accounts is a SEED — prisma/seed/Account_Groups.sql. On a
--  fresh database, and on the shadow database `migrate dev` replays into,
--  accounts.acc_group_master is empty while this migration runs, so there is
--  nothing here to hang a ledger under. A migration that inserted directly
--  would either fail the replay or quietly map nothing.
--
--  So the mapping ships as two functions, and BOTH callers use them:
--
--      accounts.fn_ledger_map_catalogue()  role -> ledger name, and how to
--                                          create that ledger if it is absent.
--                                          The 22-row configuration itself.
--      accounts.fn_seed_ledger_map()       applies the catalogue. Idempotent.
--
--  This file calls it once, in "skip if the chart is not there yet" mode, so
--  an existing database is mapped at migrate time and a fresh one is not
--  failed. prisma/seed/Acc_Ledger_Map.sql calls it in strict mode on every
--  boot, straight after Account_Groups.sql — which is what actually maps a
--  fresh database, and what re-asserts the map on every deploy afterwards.
--
--  Changing a mapping means CREATE OR REPLACE on the catalogue in a NEW
--  migration, then letting the seed re-run. Do not edit this file once it has
--  been applied — see §5 at the bottom for what is deliberately not here.
--
--  ── The one thing to understand before reading the catalogue ─────────────
--  There is NO TRIGGER on acc_ledger_map. 20260911070000's header promises
--  accounts.fn_check_role_ledger and a guard built on it; neither was ever
--  written (the 20260911071000 folder it names does not exist, and pg_proc
--  has no such function). The check lives in TypeScript —
--  ledger-role.helper.ts — which nothing reaches when rows arrive by SQL.
--  So nothing in the database stops SALES being pointed at a bank account.
--
--  fn_seed_ledger_map therefore checks the fit ITSELF, against each role's own
--  alr_want_type / alr_want_duty / alr_want_nature, and a pair that does not
--  fit ABORTS rather than being skipped: a silently skipped role is exactly
--  the null that caused this. If the guard is ever added those checks become
--  redundant, which is the right direction for them to become wrong in.
--
--  ── Scope columns ────────────────────────────────────────────────────────
--  alm_company_id / alm_branch_id are left NULL on every row. The chart is
--  shared, so a role has one answer for the whole business; those columns
--  exist so a single company or branch could be given its own ledger later
--  without a migration, and the resolver already prefers the more specific
--  row. alm_supply_nature is NULL too — set it only if the chart ever
--  separates 'Local Sales' from 'Interstate Sales'. This one does not.
--
--  PostgreSQL 18.
-- ═══════════════════════════════════════════════════════════════════════════


-- ═══════════════════════════════════════════════════════════════════════════
--  1 · THE CATALOGUE — the configuration, and the only place to edit it
--
--  One row per role in accounts.acc_ledger_role. Each names the ledger that
--  role posts to, plus what that ledger must look like if it has to be
--  created: its led_ledger_type, its led_gst_duty_head, and the global
--  account group it hangs under.
--
--  Ten of these ledgers already exist on a chart that has been in use — Sales
--  Account, Sales Return, the four Output taxes, Round Off, Discount Allowed,
--  Bad Debts Written Off, Customer Advances Received. They are listed anyway,
--  with the shape they already have, so that a FRESH database gets them too;
--  fn_seed_ledger_map matches by name and leaves an existing one untouched.
--  The other twelve do not exist anywhere yet.
--
--  ── Why the tax ledgers sit under a Liabilities group ────────────────────
--  Input CGST is economically a receivable, but Tally puts both sides under
--  Duties & Taxes and so does this chart — and the role does not care: the tax
--  roles set alr_want_duty and alr_want_type and leave alr_want_nature NULL,
--  precisely so the chart may place them where the accountant expects.
--
--  ── The two FUTURE roles ─────────────────────────────────────────────────
--  TCS_PAYABLE and TDS_PAYABLE are in acc_ledger_role's FUTURE group and
--  nothing posts to them yet. They are here anyway, because a role with a
--  ledger costs nothing and the alternative is discovering the gap on the day
--  TDS arrives. The cost is two ledgers sitting at zero in the trial balance.
--  If that is unwanted, drop their two rows — this is the only place either
--  name appears — and fn_seed_ledger_map will then refuse the pair as an
--  uncovered role, which is the loud failure that decision deserves.
-- ═══════════════════════════════════════════════════════════════════════════
CREATE OR REPLACE FUNCTION accounts.fn_ledger_map_catalogue()
